DEFAULT_EXTENSION = "ленточное наращивание (базовый вариант)"


def get_extension_type(texture: str, density: str) -> str:
    """Возвращает вид наращивания по текстуре и густоте"""
    return EXTENSION_TABLE.get((texture, density), DEFAULT_EXTENSION)